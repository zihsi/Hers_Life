/**
 * Build the single browser entry for the Hers Life composition bundle.
 * Run from the repository root: node scripts/build-client.mjs
 * The source client chunks remain owned by their original child packages.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sources = [
  'dsh-ming-memory/client.js',
  'dsh-ming-graph/client.js',
  'dsh-ming-mousepet/client.js',
]
const chunks = []
for (const relative of sources) {
  chunks.push(`/* ---- bundled from ${relative} ---- */\\n` + await readFile(path.join(root, relative), 'utf8'))
}
const bridge = `
/* ---- Hers Life client composition ---- */
window.__ModuleLoader__.load({
  id: 'dsh-hers-life',
  factory(require) {
    const children = [
      ['dsh-ming-memory', require('dsh-ming-memory')],
      ['dsh-ming-graph', require('dsh-ming-graph')],
      ['dsh-ming-mousepet', require('dsh-ming-mousepet')],
    ]
    return {
      name: 'hers-life-client',
      async apply(ctx) {
        for (const [id, mod] of children) {
          if (!mod || typeof mod.apply !== 'function') {
            throw new Error('[dsh-hers-life] missing client module: ' + id)
          }
          const plugin = Object.assign((childCtx) => mod.apply(childCtx), {
            name: id,
            inject: Array.isArray(mod.inject) ? mod.inject : [],
          })
          await ctx.plugin(plugin)
        }
      },
    }
  },
})
`
const output = `/* Generated by scripts/build-client.mjs. Do not edit by hand. */\\n${chunks.join('\\n;\\n')}\\n;\\n${bridge}`
await writeFile(path.join(root, 'client.js'), output, 'utf8')
console.log(`Built client.js from ${sources.length} child client entries (${output.length} characters).`)
